package za.co.dfraas.entity;

import java.time.OffsetDateTime;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.ForeignKey;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

import lombok.Getter;
import lombok.Setter;

/**
 * A single preserved artifact — the hub entity. It points at the blob in MinIO, carries
 * the digest that blob is expected to have, and records the classification it was
 * preserved under, the source that produced it, and the interval of activity it covers.
 *
 * <p><strong>Preserved independently of any alert.</strong> Items stream in continuously
 * from registered {@link EvidenceSource}s; a {@link TriggerEvent} does not cause them to
 * exist, it gathers the ones already preserved whose {@link #getEventStart() coverage
 * window} overlaps it. That association is many-to-many and reviewable, so it lives in
 * {@link EvidenceLink} rather than in a foreign key here — the {@code trigger_event_id}
 * column this entity used to map was dropped in changeset {@code 0005}, because a single FK
 * both capped an artifact at one incident and presented an inferred correlation in the
 * same shape as an observed cause.
 *
 * <p>Mirrors Liquibase changesets {@code 0003-create-evidence-item-table} and
 * {@code 0004-create-evidence-source-and-coverage-window}. Because
 * {@code spring.jpa.hibernate.ddl-auto=validate}, any drift between this class and those
 * changesets fails application startup, so they must be edited together.
 *
 * <p>Rows here are effectively append-only apart from {@link #status} and
 * {@link #currentHash}. Nothing else about a preserved artifact can legitimately change:
 * re-pointing {@link #storageRef} at a different object would substitute one piece of
 * evidence for another while keeping its custody history, which is the single most
 * damaging edit possible in this schema — hence {@code updatable = false} on it, on both
 * foreign keys, and on the coverage window, which is an assertion made at collection time
 * and not a field to be tuned afterwards until a correlation returns the desired result.
 *
 * <p><strong>Not modelled here, deliberately:</strong> who preserved it and when it was
 * touched. Those belong to {@code CustodyEvent}, which is append-only and carries
 * {@code performedBy}; duplicating a "last modified by" column here would create a second,
 * mutable account of the same fact, and the two would eventually disagree.
 */
@Entity
@Table(name = "evidence_item")
@Getter
@Setter
public class EvidenceItem {

	/**
	 * Generated by Hibernate rather than by the column's {@code gen_random_uuid()} default,
	 * matching {@link WorkGroup} and {@link TriggerEvent}. Having the id before flush is
	 * what lets ingestion derive a storage key and append the opening custody event in the
	 * same transaction, without a round trip to read the value back.
	 */
	@Id
	@GeneratedValue(strategy = GenerationType.UUID)
	@Column(name = "id", nullable = false, updatable = false)
	private UUID id;

	/**
	 * The classification this artifact was preserved under (K-FFRaaS work group).
	 * Mandatory: unclassified evidence cannot be routed, retained or released, so an item
	 * without one has no defensible handling policy.
	 *
	 * <p>Where classification needs human review before storage (README open question 1),
	 * the answer is a work group that means "not yet classified", not a null FK. That is
	 * not the same move as the placeholder {@code TriggerEvent} rejected in open question
	 * 2: "unclassified" is a truthful classification state, whereas a synthetic trigger
	 * event would assert that an alert fired when none did.
	 *
	 * <p>{@code LAZY} because most reads of an item do not need the work group's name, and
	 * {@code spring.jpa.open-in-view=false} means an unwanted fetch fails loudly in a test
	 * rather than quietly issuing N+1 queries in production. Callers that do need it should
	 * fetch-join.
	 */
	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(
			name = "work_group_id",
			nullable = false,
			updatable = false,
			foreignKey = @ForeignKey(name = "fk_evidence_item_work_group"))
	private WorkGroup workGroup;

	/**
	 * The registered collector that produced this artifact, or {@code null} when a person
	 * preserved it rather than a stream.
	 *
	 * <p>Nullable for the same reason the old {@code triggerEvent} field was: manual
	 * preservation and compliance holds have no collector behind them, and inventing a
	 * "manual" source row would assert that a collector exists. Provenance survives the
	 * null because every item gets a mandatory opening {@code CustodyEvent} carrying
	 * {@code performedBy}.
	 *
	 * <p>{@code LAZY}, as with {@link #workGroup}: most reads do not need the source's
	 * registration details, and {@code spring.jpa.open-in-view=false} means an unwanted
	 * fetch fails loudly in a test rather than quietly issuing N+1 queries in production.
	 */
	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(
			name = "evidence_source_id",
			updatable = false,
			foreignKey = @ForeignKey(name = "fk_evidence_item_evidence_source"))
	private EvidenceSource evidenceSource;

	/**
	 * The producer's own identifier for this artifact, and the dedupe key for streamed
	 * ingestion — the evidence-side equivalent of
	 * {@link TriggerEvent#getExternalEventId()}.
	 *
	 * <p>Unique in combination with {@link #evidenceSource} only, since an artifact id is
	 * meaningful only within the source that issued it. Postgres treats NULLs as distinct
	 * in a unique constraint, which is exactly right here: manually preserved items carry
	 * null in both and never collide, while a source redelivering
	 * {@code auth-2026-09-05-14} is rejected on the second attempt.
	 *
	 * <p>This matters more than it did under the reactive design. Kafka is at-least-once
	 * and the artifact stream is orders of magnitude larger than the alert stream, so
	 * redelivery is a daily occurrence rather than an edge case. Until this column existed
	 * the only thing standing against a duplicate item was
	 * {@code uq_evidence_item_storage_ref}, which helps only if the storage key happens to
	 * be derived deterministically from the artifact — a property nothing enforced.
	 */
	@Column(name = "source_artifact_id", updatable = false, length = 255)
	private String sourceArtifactId;

	/**
	 * Start of the interval of activity this artifact actually covers, as asserted by the
	 * source; {@code null} when unknown.
	 *
	 * <p><strong>The axis correlation runs along, and emphatically not {@link #createdAt}.</strong>
	 * An hourly log bundle rolled at 15:00 and preserved at 15:02 covers 14:00–15:00.
	 * Correlating an alert that fired at 14:30 against {@code createdAt} would miss that
	 * bundle entirely while matching bundles containing nothing relevant.
	 *
	 * <p>Sender-asserted, and treated with the same suspicion as
	 * {@link TriggerEvent#getFiredAt()} — kept <em>alongside</em> {@code createdAt} rather
	 * than replacing it. A source with a skewed clock misplaces its own evidence in time,
	 * and the gap between the two is what makes that visible.
	 *
	 * <p>Null means the window is unknown, not that the item is deficient: it is still fully
	 * preserved evidence, it simply cannot be correlated automatically and can only be
	 * linked to an alert by hand. Making this mandatory was rejected — it would either
	 * reject legitimate evidence at ingest, or force a backfill inventing a coverage window
	 * from {@code createdAt}, which asserts when an artifact's contents were produced on the
	 * basis of when we happened to store it.
	 *
	 * <p>A point-in-time artifact (a memory dump, a single transaction record) sets this and
	 * {@link #eventEnd} to the same instant, which is why the correlation index builds its
	 * range with inclusive bounds — a half-open range over a zero-length interval is empty
	 * and would overlap nothing.
	 */
	@Column(name = "event_start", updatable = false)
	private OffsetDateTime eventStart;

	/**
	 * End of the coverage window. Null exactly when {@link #eventStart} is null, and never
	 * earlier than it — {@code ck_evidence_item_coverage_window} enforces both, because half
	 * a window is worse than none: it looks answerable to a correlation query and answers
	 * wrongly.
	 */
	@Column(name = "event_end", updatable = false)
	private OffsetDateTime eventEnd;

	/**
	 * The MinIO object key this artifact is stored under — the one pointer from metadata to
	 * the bytes themselves.
	 *
	 * <p>Unique, because two items sharing a key would mean two custody chains and two
	 * retention decisions governing one object; deleting under one would silently gut the
	 * other. Sized for the 1024-byte S3 key limit so a legitimate key is never truncated.
	 *
	 * <p>Stores a key, not a URL: endpoint, bucket and credentials are deployment
	 * configuration ({@code dfraas.storage.*}) and change with the environment, while the
	 * key must stay valid for the lifetime of the evidence.
	 */
	@Column(name = "storage_ref", nullable = false, updatable = false, unique = true, length = 1024)
	private String storageRef;

	/**
	 * Lowercase hex SHA-256 of the stored object, computed on ingest before anything else
	 * touches the bytes (SecureRS), and re-computed and compared on every read or export.
	 * A database CHECK enforces the format, so a malformed digest is rejected even on a
	 * write that bypasses this application.
	 *
	 * <p>"Current" rather than "original" because a legitimate operation can change the
	 * bytes — envelope-key rotation, re-encryption, an approved redaction. Each such change
	 * writes a {@code CustodyEvent} carrying {@code previousHash} and {@code newHash}, so
	 * the original digest is never lost; it is the first link of that chain rather than a
	 * second column here that would only ever restate it.
	 */
	@Column(name = "current_hash", nullable = false, length = 64)
	private String currentHash;

	/**
	 * Persisted by name, not ordinal — see {@link EvidenceStatus}. An ordinal mapping would
	 * make reordering the enum constants a silent, undetectable corruption of every
	 * existing row, in a table whose contents may be evidence.
	 */
	@Enumerated(EnumType.STRING)
	@Column(name = "status", nullable = false, length = 32)
	private EvidenceStatus status;

	/**
	 * When the artifact was preserved, stamped by the database clock via the column
	 * default. {@code @Generated(INSERT)} is what makes the default fire: without it
	 * Hibernate would send the field as {@code null} and the NOT NULL constraint would
	 * reject the row.
	 *
	 * <p>Deliberately the database's clock and not the JVM's — a skewed application host
	 * must not be able to influence a timestamp that may later be evidence. Note this is
	 * when <em>we</em> preserved the artifact, which is not when the artifact was created
	 * on the system it came from; that belongs with the collected metadata, not here.
	 */
	@Generated(event = EventType.INSERT)
	@Column(name = "created_at", nullable = false, insertable = false, updatable = false)
	private OffsetDateTime createdAt;

	/**
	 * Identity by primary key once assigned, matching the other entities. Two unsaved
	 * instances are never equal, which is the correct answer — they are two separate
	 * objects that have not yet been given an identity.
	 */
	@Override
	public boolean equals(Object other) {
		if (this == other) {
			return true;
		}
		if (!(other instanceof EvidenceItem that)) {
			return false;
		}
		return id != null && id.equals(that.id);
	}

	/**
	 * Constant per type rather than derived from {@code id}, so an instance added to a
	 * {@code HashSet} before persist is not stranded in the wrong bucket once Hibernate
	 * assigns the id.
	 */
	@Override
	public int hashCode() {
		return EvidenceItem.class.hashCode();
	}

	/**
	 * Deliberately omits the lazy associations — touching them here would fire a query from
	 * whatever logging statement happened to interpolate this object, or throw outside a
	 * session.
	 */
	@Override
	public String toString() {
		return "EvidenceItem{id=" + id + ", storageRef='" + storageRef + "', status=" + status + "}";
	}
}
