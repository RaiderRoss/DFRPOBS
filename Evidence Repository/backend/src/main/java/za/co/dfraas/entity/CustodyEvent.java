package za.co.dfraas.entity;

import java.time.OffsetDateTime;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.ForeignKey;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

import lombok.Getter;
import lombok.Setter;

/**
 * One entry in an {@link EvidenceItem}'s chain of custody — who did what to an artifact,
 * when, and what its digest was before and after.
 *
 * <p>Mirrors Liquibase changeset {@code 0006-create-custody-event}. Because
 * {@code spring.jpa.hibernate.ddl-auto=validate}, any drift between this class and that
 * changeset fails application startup, so the two must be edited together.
 *
 * <p><strong>Append-only, and here that is enforced rather than documented.</strong> Every
 * other table in this schema is described as append-only and relies on nobody calling the
 * {@code delete} and setters they inherit (README open question 8). A custody ledger cannot
 * rest on that, because its only value is that it cannot be quietly improved after the fact.
 * Three things hold it in place, at increasing distance from this class:
 *
 * <ul>
 *   <li>Every column is {@code updatable = false}, so Hibernate simply omits them from any
 *       UPDATE it would generate. Mutating a loaded entry is not rejected, it is ignored —
 *       which is a deliberate choice of failure mode: a caller who tries has changed
 *       nothing, rather than having thrown an exception someone might have been tempted to
 *       catch.</li>
 *   <li>{@link #entryHash} covers this row's contents and {@link #prevEntryHash} binds it to
 *       the entry before it, so an edit made outside Hibernate — a direct UPDATE, a DBA at a
 *       psql prompt — no longer agrees with the digest stored beside it.
 *       {@code CustodyChainService.verify} is what surfaces that.</li>
 *   <li>What the chain cannot do is detect its own <em>end</em> being truncated. That needs
 *       the head hash witnessed outside this database, and it is deliberately out of scope
 *       here rather than quietly assumed — see {@code 0006-create-custody-event}.</li>
 * </ul>
 *
 * <p><strong>Nothing here is a setter you should reach for after a flush.</strong> The
 * setters exist so {@code CustodyChainService.append} can assemble an entry before it is
 * hashed; that service is the only thing that should construct one, because sequence,
 * prev_entry_hash and entry_hash are not independent fields but a computed unit, and a row
 * assembled by hand will not verify.
 */
@Entity
@Table(
		name = "custody_event",
		uniqueConstraints = @UniqueConstraint(
				name = "uq_custody_event_item_sequence",
				columnNames = {"evidence_item_id", "sequence"}))
@Getter
@Setter
public class CustodyEvent {

	/**
	 * Generated by Hibernate rather than by the column's {@code gen_random_uuid()} default,
	 * matching the other entities. Deliberately <em>not</em> part of the canonical form: the
	 * chain's identity comes from the item and the position, and hashing a surrogate key
	 * would tie every digest to a value that carries no meaning.
	 */
	@Id
	@GeneratedValue(strategy = GenerationType.UUID)
	@Column(name = "id", nullable = false, updatable = false)
	private UUID id;

	/**
	 * The artifact whose chain this entry belongs to.
	 *
	 * <p>{@code LAZY}, as on the other associations, and reading the id off the proxy is
	 * enough for both the canonical form and the API: Hibernate answers
	 * {@code getEvidenceItem().getId()} without initialising it, so hashing an entry does
	 * not become a second query.
	 */
	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(
			name = "evidence_item_id",
			nullable = false,
			updatable = false,
			foreignKey = @ForeignKey(name = "fk_custody_event_evidence_item"))
	private EvidenceItem evidenceItem;

	/**
	 * Position within this item's chain, contiguous from 0.
	 *
	 * <p>Inside the canonical form, so an entry cannot be moved to another position without
	 * failing verification, and checked for contiguity by
	 * {@code CustodyChainService.verify} — which is the only thing that catches a deleted
	 * middle entry, since the rows either side of the hole are individually valid.
	 */
	@Column(name = "sequence", nullable = false, updatable = false)
	private long sequence;

	/**
	 * Persisted by name, not ordinal — see {@link CustodyAction}. An ordinal mapping would
	 * make reordering the enum constants a silent corruption of every existing row, and here
	 * it would also invalidate every digest computed over the old ordering.
	 */
	@Enumerated(EnumType.STRING)
	@Column(name = "action", nullable = false, updatable = false, length = 32)
	private CustodyAction action;

	/**
	 * Who performed the action, or {@code null} when the honest answer is "the ingestion
	 * pipeline" — the same rule as {@link EvidenceLink#getLinkedBy()}.
	 *
	 * <p>Free text, and inside the digest, which is why the canonical form length-prefixes
	 * every field: an attribution that could contain something shaped like a field boundary
	 * would be a way of making one entry hash as another.
	 *
	 * <p>TODO: becomes a foreign key to {@code app_user} once that table exists. The third
	 * such placeholder, with {@code EvidenceLink.linkedBy} and {@code reviewedBy}.
	 */
	@Column(name = "performed_by", updatable = false, length = 255)
	private String performedBy;

	/**
	 * When the action happened, as claimed by the application — the one timestamp in this
	 * schema that is not the database's own clock.
	 *
	 * <p>It has to be, because {@link #entryHash} covers it and must be computed before the
	 * INSERT that carries it: a database-generated value could only be hashed by reading it
	 * back and issuing an UPDATE, which is the single operation this table exists to
	 * forbid. {@link #recordedAt} keeps the database's account of the same entry, and the
	 * gap between the two is a signal in itself.
	 *
	 * <p>The opening {@link CustodyAction#CREATED} entry is passed
	 * {@code EvidenceItem.createdAt}, so the first link of every chain carries a database
	 * clock regardless.
	 *
	 * <p><strong>Rendered into the canonical form as UTC truncated to microseconds</strong>,
	 * because that is all a Postgres {@code timestamptz} keeps — neither the offset it was
	 * written with nor anything finer survives. {@code CustodyChainService.append} normalises
	 * the value before storing it, so the field in memory matches the column exactly and an
	 * entry verifies identically before and after a round trip.
	 */
	@Column(name = "occurred_at", nullable = false, updatable = false)
	private OffsetDateTime occurredAt;

	/**
	 * The database's account of when this entry arrived, stamped by the column default.
	 * {@code @Generated(INSERT)} is what makes the default fire; without it Hibernate would
	 * send {@code null} and the NOT NULL constraint would reject the row.
	 *
	 * <p>Deliberately <em>outside</em> the digest. It is not the application's claim to make,
	 * and including it would require exactly the read-back-then-update cycle
	 * {@link #occurredAt} explains. It is the value to trust when the two disagree.
	 */
	@Generated(event = EventType.INSERT)
	@Column(name = "recorded_at", nullable = false, insertable = false, updatable = false)
	private OffsetDateTime recordedAt;

	/**
	 * The artifact's digest before the action, or {@code null} when the action did not change
	 * the bytes — which is most actions.
	 *
	 * <p>Named for the artifact rather than as {@code previousHash}, because this entity
	 * carries two unrelated pairs of hashes and a {@code previousHash} sitting beside
	 * {@link #prevEntryHash} would be read as part of the chain. One pair is about the
	 * exhibit, the other about the ledger.
	 */
	@Column(name = "artifact_hash_before", updatable = false, length = 64)
	private String artifactHashBefore;

	/**
	 * The artifact's digest after the action. Set with {@link #artifactHashBefore} left null
	 * on the opening entry, where there was no prior state — which is what anchors
	 * {@link EvidenceItem#getCurrentHash()} into the chain. That column is mutable by design
	 * (key rotation, re-encryption, an approved redaction); these are the immutable record of
	 * every value it has held.
	 */
	@Column(name = "artifact_hash_after", updatable = false, length = 64)
	private String artifactHashAfter;

	/**
	 * The preceding entry's {@link #entryHash} — the link that makes this a chain.
	 *
	 * <p>The first entry carries {@code CustodyChainService.GENESIS_HASH} (64 {@code '0'}
	 * characters) rather than null, and {@code ck_custody_event_origin} requires that value at
	 * sequence 0 — so a chain cannot be re-rooted at some predecessor that is nowhere in the
	 * ledger. A nullable column would put a special case for the origin into every
	 * verification pass, and a special case in verification code is where a forged origin
	 * eventually hides.
	 */
	@Column(name = "prev_entry_hash", nullable = false, updatable = false, length = 64)
	private String prevEntryHash;

	/**
	 * SHA-256 over {@link #prevEntryHash} concatenated with this entry's canonical form —
	 * see {@code CustodyChainService.canonicalV1} for exactly what that covers, in what
	 * order, and why it is frozen.
	 *
	 * <p>Stored rather than derived on read, which is the entire point: a row whose contents
	 * were edited outside this application no longer agrees with the digest written beside
	 * it.
	 */
	@Column(name = "entry_hash", nullable = false, updatable = false, length = 64)
	private String entryHash;

	/**
	 * Which version of the canonical form {@link #entryHash} was computed under, selected per
	 * row so that history keeps verifying under the rules it was written under.
	 *
	 * <p>The canonical form is frozen: changing field order, encoding or inclusion changes
	 * every digest it produces, so an improvement applied in place would invalidate the whole
	 * ledger and be indistinguishable from tampering. New rules go in a new version and old
	 * rows keep theirs. Rows are never migrated between versions — that would mean
	 * recomputing stored digests, which is forgery with good intentions.
	 */
	@Column(name = "canonical_version", nullable = false, updatable = false)
	private short canonicalVersion;

	/**
	 * Free-text account of the action, for a person to read: why a status was changed, what a
	 * re-verification found, who authorised a hold.
	 *
	 * <p>Covered by the digest only as its own SHA-256, never inlined. Free text can contain
	 * anything, including something shaped like the canonical form's field encoding, and
	 * hashing it first keeps its content away from the boundary logic entirely — while also
	 * keeping the canonical form a fixed size however much prose an operator writes.
	 */
	@Column(name = "detail", updatable = false, columnDefinition = "text")
	private String detail;

	/**
	 * Identity by primary key once assigned, matching the other entities. Two unsaved
	 * instances are never equal — and deliberately not identity by
	 * {@code (evidenceItem, sequence)} even though the database treats that as unique: two
	 * unsaved entries claiming one position are a concurrent-append bug for
	 * {@code uq_custody_event_item_sequence} to reject, not a coincidence to smooth over in
	 * memory.
	 */
	@Override
	public boolean equals(Object other) {
		if (this == other) {
			return true;
		}
		if (!(other instanceof CustodyEvent that)) {
			return false;
		}
		return id != null && id.equals(that.id);
	}

	/**
	 * Constant per type rather than derived from {@code id}, so an instance added to a
	 * {@code HashSet} before persist is not stranded in the wrong bucket once Hibernate
	 * assigns the id.
	 */
	@Override
	public int hashCode() {
		return CustodyEvent.class.hashCode();
	}

	/**
	 * Deliberately omits the lazy association — touching it here would fire a query from
	 * whatever logging statement interpolated this object, or throw outside a session. The
	 * entry hash is abbreviated because a log line is for locating an entry, not for
	 * verifying one.
	 */
	@Override
	public String toString() {
		return "CustodyEvent{id=" + id
				+ ", sequence=" + sequence
				+ ", action=" + action
				+ ", entryHash=" + (entryHash == null ? null : entryHash.substring(0, 12) + "...") + '}';
	}
}
