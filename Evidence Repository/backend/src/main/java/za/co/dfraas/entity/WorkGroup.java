package za.co.dfraas.entity;

import java.time.OffsetDateTime;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

import lombok.Getter;
import lombok.Setter;

/**
 * The business-unit classification every {@code EvidenceItem} is tagged with (K-FFRaaS
 * "work group" concept).
 *
 * <p>Mirrors Liquibase changeset {@code 0001-create-work-group-table}. Because
 * {@code spring.jpa.hibernate.ddl-auto=validate}, any drift between this class and that
 * changeset fails application startup rather than silently altering an audited table —
 * so the two must be edited together.
 */
@Entity
@Table(name = "work_group")
@Getter
@Setter
public class WorkGroup {

	/**
	 * Generated by Hibernate rather than by the column's {@code gen_random_uuid()} default.
	 *
	 * <p>Both work, but they are not equivalent: DB-side generation would force
	 * {@code insertable = false} plus a SELECT after every insert to read the value back.
	 * Generating in Java avoids that round trip and makes the id available before flush.
	 * The column default stays in the changeset as a safety net for inserts that do not go
	 * through JPA — the Liquibase seed data in {@code 0001-2} relies on it.
	 */
	@Id
	@GeneratedValue(strategy = GenerationType.UUID)
	@Column(name = "id", nullable = false, updatable = false)
	private UUID id;

	@Column(name = "name", nullable = false, length = 255)
	private String name;

	@Column(name = "classification_code", nullable = false, unique = true, length = 64)
	private String classificationCode;

	/**
	 * Populated by the column's {@code now()} default, not by application code.
	 *
	 * <p>{@code @Generated(INSERT)} is what makes that work: without it Hibernate would
	 * include the field in the INSERT as {@code null}, the default would never fire, and
	 * the NOT NULL constraint would reject the row. With it, the column is left out of the
	 * INSERT and read back afterwards.
	 *
	 * <p>Keeping the clock in the database rather than in the JVM matters here — this is an
	 * audited table, and a skewed application host should not be able to influence a
	 * timestamp that may later be evidence.
	 */
	@Generated(event = EventType.INSERT)
	@Column(name = "created_at", nullable = false, insertable = false, updatable = false)
	private OffsetDateTime createdAt;

	/**
	 * Identity is the surrogate key only, and a transient instance is never equal to
	 * anything but itself. {@code hashCode} is deliberately constant per type rather than
	 * derived from {@code id}: the id is assigned at persist time, and a hash that changed
	 * at that moment would strand the entity in any {@code HashSet} it had been added to
	 * beforehand.
	 */
	@Override
	public boolean equals(Object other) {
		if (this == other) {
			return true;
		}
		if (!(other instanceof WorkGroup that)) {
			return false;
		}
		return id != null && id.equals(that.id);
	}

	@Override
	public int hashCode() {
		return WorkGroup.class.hashCode();
	}

	@Override
	public String toString() {
		return "WorkGroup{id=" + id + ", classificationCode='" + classificationCode + "'}";
	}
}
